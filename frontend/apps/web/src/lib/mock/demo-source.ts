import type { DataSource } from "@/lib/api/source";
import { NotFoundError } from "@/lib/api/source";
import type { PresetId, Score, TrackDetail, TrackSummary, ValueGrid } from "@/lib/api/types";
import { GRID_MAX, NO_DATA, PRESET_IDS } from "@/lib/api/types";

import { DEMO_TRACKS, type DemoTrackDef } from "./catalogue";
import { audioKeyText, buildScore, buildTranscript, frameDurationSeconds, THEME_KEY } from "./mapping";
import { GRID_COLS, GRID_ROWS } from "./world";

const DEMO_CREDIT = "Synthetic demo field generated by TeraTones. Not NASA data; replaced by EIC imagery when the backend is connected.";

const gridCache = new Map<string, ValueGrid[]>();
const scoreCache = new Map<string, Score>();

function grids(def: DemoTrackDef): ValueGrid[] {
  const cached = gridCache.get(def.id);
  if (cached) return cached;
  const count = def.frame_labels.length;
  const result = def.frame_labels.map((_, frame) => {
    const t = count > 1 ? frame / (count - 1) : 0;
    const cells = new Uint8Array(GRID_COLS * GRID_ROWS);
    for (let r = 0; r < GRID_ROWS; r++) {
      for (let c = 0; c < GRID_COLS; c++) {
        const value = def.generate((c + 0.5) / GRID_COLS, (r + 0.5) / GRID_ROWS, t);
        cells[r * GRID_COLS + c] = value === null ? NO_DATA : Math.round(value * GRID_MAX);
      }
    }
    return {
      cols: GRID_COLS,
      rows: GRID_ROWS,
      cells,
      real_min: def.legend.min,
      real_max: def.legend.max,
      unit: def.legend.unit,
    };
  });
  gridCache.set(def.id, result);
  return result;
}

function score(def: DemoTrackDef, preset: PresetId): Score {
  const key = `${def.id}:${preset}`;
  const cached = scoreCache.get(key);
  if (cached) return cached;
  const result = buildScore({
    trackId: def.id,
    theme: def.theme,
    legend: def.legend,
    labels: def.frame_labels,
    grids: grids(def),
    preset,
  });
  scoreCache.set(key, result);
  return result;
}

function summary(def: DemoTrackDef): TrackSummary {
  return {
    id: def.id,
    title: def.title,
    theme: def.theme,
    summary: def.summary,
    date_range: def.date_range,
    frame_count: def.frame_labels.length,
    duration_s: def.frame_labels.length * frameDurationSeconds(THEME_KEY[def.theme].bpm),
    thumbnail_url: null,
    credit: DEMO_CREDIT,
    source_url: null,
    calibrated: true,
    synthetic: true,
  };
}

function find(id: string): DemoTrackDef {
  const def = DEMO_TRACKS.find((t) => t.id === id);
  if (!def) throw new NotFoundError(`Track "${id}" not found`);
  return def;
}

export function createDemoSource(): DataSource {
  return {
    kind: "demo",
    async listTracks() {
      return DEMO_TRACKS.map(summary);
    },
    async getTrack(id): Promise<TrackDetail> {
      const def = find(id);
      return {
        ...summary(def),
        description: def.description,
        audio_key: audioKeyText(def.legend),
        legend: def.legend,
        presets: [...PRESET_IDS],
        frame_labels: def.frame_labels,
        transcript: buildTranscript(score(def, "musical"), def.legend),
      };
    },
    async getScore(id, preset) {
      return score(find(id), preset);
    },
    async getGrid(id, frame) {
      const all = grids(find(id));
      const grid = all[Math.min(all.length - 1, Math.max(0, frame))];
      if (!grid) throw new NotFoundError(`Frame ${frame} not found`);
      return grid;
    },
    frameImageUrl() {
      return null;
    },
  };
}
